/*
 * The Direct3D 6 fixed-function subset the game uses, as one shader pair, plus the composition passes.
 * Compiled once when the device is created.
 */
#include "d3d11_shaders.h"

const char d3d11_shader_source[] =
    "cbuffer Frame : register(b0) { float4 target; };\n"
    "cbuffer Draw : register(b1) { uint flags; uint blend_mode; uint alpha_func; float alpha_ref; float4 fog_color; };\n"
    "cbuffer PassConstants : register(b2) { float4 pass_rect; float4 pass_uv; float4 pass_color; float pass_depth; float3 pass_pad; };\n"
    "Texture2D tex0 : register(t0);\n"
    "Texture2D gamma_lut : register(t1);\n"
    /* World textures: slices of up to sixteen arrays (one per size), picked per vertex with the sampler for the
     * vertex's address modes, so draws with different textures and wrap/clamp share one batch. SampleGrad: the
     * gradients come from outside the branches. */
    "Texture2DArray world0 : register(t2); Texture2DArray world1 : register(t3);\n"
    "Texture2DArray world2 : register(t4); Texture2DArray world3 : register(t5);\n"
    "Texture2DArray world4 : register(t6); Texture2DArray world5 : register(t7);\n"
    "Texture2DArray world6 : register(t8); Texture2DArray world7 : register(t9);\n"
    "Texture2DArray world8 : register(t10); Texture2DArray world9 : register(t11);\n"
    "Texture2DArray world10 : register(t12); Texture2DArray world11 : register(t13);\n"
    "Texture2DArray world12 : register(t14); Texture2DArray world13 : register(t15);\n"
    "Texture2DArray world14 : register(t16); Texture2DArray world15 : register(t17);\n"
    "SamplerState samp0 : register(s0);\n"
    "SamplerState samp_clamp_u : register(s1);\n"
    "SamplerState samp_clamp_v : register(s2);\n"
    "SamplerState samp_clamp_uv : register(s3);\n"
    "SamplerState samp_device : register(s4);\n"
    /* Water refraction and Enhanced sky (ce_effects.h): fx_water = (1/width, 1/height, strength, height/width),
     * fx_sky = (camera u, camera v, plane height, fog low), fx_sky2.x = fog high, fx_water2.x = 1 / FX_WATER_RHW_METRE, fx_water3 = the uv
     * rectangle of the 3D viewport the shifted sample may not leave (fx_water_scene_bounds). */
    "cbuffer Effects : register(b3) { float4 fx_water; float4 fx_sky; float4 fx_sky2; float4 fx_water2; float4 fx_water3; };\n"
    "Texture2D water_waves : register(t18);\n"
    "Texture2D scene_behind : register(t19);\n"
    "SamplerState samp_linear : register(s5);\n"
    "#define F_TEXTURED 1u\n"
    "#define F_TEX_ALPHA 2u\n"
    "#define F_KEY_TEST 4u\n"
    "#define F_ALPHA_TEST 8u\n"
    "#define F_FOG 16u\n"
    "#define F_SPECULAR 32u\n"
    "#define F_FLAT 64u\n"
    "#define F_DEBUG_TEXTURE 128u\n"
    "#define F_DEBUG_VERTEX 256u\n"
    "#define F_DEBUG_DEPTH 512u\n"
    "#define F_AO_CLOSED 1024u\n"
    "struct VSIn { float4 pos : POSITION; float4 diffuse : COLOR0; float4 specular : COLOR1; float2 uv : TEXCOORD0;\n"
    "              uint layer : TEXCOORD1; };\n"
    "struct PSIn {\n"
    "  float4 pos : SV_Position;\n"
    "  float4 diffuse : COLOR0;\n"
    "  float4 specular : COLOR1;\n"
    "  nointerpolation float4 flat_diffuse : COLOR2;\n"
    "  nointerpolation float4 flat_specular : COLOR3;\n"
    "  float2 uv : TEXCOORD0;\n"
    "  nointerpolation uint layer : TEXCOORD1;\n"
    "  noperspective float rhw : TEXCOORD2;\n"
    "};\n"
    /* Pre-transformed vertices: Direct3D 6 pixel centres are integers, D3D11's are at +0.5. */
    "PSIn vs_tl(VSIn v) {\n"
    "  PSIn o;\n"
    "  float w = v.pos.w > 1e-20 ? 1.0 / v.pos.w : 1.0;\n"
    "  float2 ndc = float2((v.pos.x + 0.5) * target.z * 2.0 - 1.0, 1.0 - (v.pos.y + 0.5) * target.w * 2.0);\n"
    "  o.pos = float4(ndc * w, saturate(v.pos.z) * w, w);\n"
    "  o.diffuse = v.diffuse; o.flat_diffuse = v.diffuse;\n"
    "  o.specular = v.specular; o.flat_specular = v.specular;\n"
    "  o.uv = v.uv;\n"
    "  o.layer = v.layer;\n"
    "  o.rhw = v.pos.w;\n"
    "  return o;\n"
    "}\n"
    "float4 sample_array(uint slot, float3 c, float2 gx, float2 gy, SamplerState s) {\n"
    "  [branch] switch (slot) {\n"
    "  case 1: return world1.SampleGrad(s, c, gx, gy);\n"
    "  case 2: return world2.SampleGrad(s, c, gx, gy);\n"
    "  case 3: return world3.SampleGrad(s, c, gx, gy);\n"
    "  case 4: return world4.SampleGrad(s, c, gx, gy);\n"
    "  case 5: return world5.SampleGrad(s, c, gx, gy);\n"
    "  case 6: return world6.SampleGrad(s, c, gx, gy);\n"
    "  case 7: return world7.SampleGrad(s, c, gx, gy);\n"
    "  case 8: return world8.SampleGrad(s, c, gx, gy);\n"
    "  case 9: return world9.SampleGrad(s, c, gx, gy);\n"
    "  case 10: return world10.SampleGrad(s, c, gx, gy);\n"
    "  case 11: return world11.SampleGrad(s, c, gx, gy);\n"
    "  case 12: return world12.SampleGrad(s, c, gx, gy);\n"
    "  case 13: return world13.SampleGrad(s, c, gx, gy);\n"
    "  case 14: return world14.SampleGrad(s, c, gx, gy);\n"
    "  case 15: return world15.SampleGrad(s, c, gx, gy);\n"
    "  default: return world0.SampleGrad(s, c, gx, gy);\n"
    "  }\n"
    "}\n"
    "float4 sample_world(uint layer, float2 uv, float2 gx, float2 gy) {\n"
    "  float3 c = float3(uv, layer & 0xFFFFu);\n"
    "  uint slot = (layer >> 16) & 15u;\n"
    "  [branch] switch ((layer >> 24) & 7u) {\n"
    "  case 1: return sample_array(slot, c, gx, gy, samp_clamp_u);\n"
    "  case 2: return sample_array(slot, c, gx, gy, samp_clamp_v);\n"
    "  case 3: return sample_array(slot, c, gx, gy, samp_clamp_uv);\n"
    "  case 4: return sample_array(slot, c, gx, gy, samp_device);\n"
    "  default: return sample_array(slot, c, gx, gy, samp0);\n"
    "  }\n"
    "}\n"
    "bool alpha_pass(float a) {\n"
    "  float r = alpha_ref;\n"
    "  if (alpha_func == 1) return false;\n"
    "  if (alpha_func == 2) return a < r;\n"
    "  if (alpha_func == 3) return abs(a - r) < 0.5 / 255.0;\n"
    "  if (alpha_func == 4) return a <= r;\n"
    "  if (alpha_func == 5) return a > r;\n"
    "  if (alpha_func == 6) return abs(a - r) >= 0.5 / 255.0;\n"
    "  if (alpha_func == 7) return a >= r;\n"
    "  return true;\n"
    "}\n"
    "float4 fixed_color(PSIn i, float fog) {\n"
    "  float4 d = (flags & F_FLAT) ? i.flat_diffuse : i.diffuse;\n"
    "  float3 s = (flags & F_FLAT) ? i.flat_specular.rgb : i.specular.rgb;\n"
    "  float4 c = d;\n"
    "  uint tf = (i.layer >> 20) & 7u;\n"
    "  float2 gx = ddx(i.uv), gy = ddy(i.uv);\n"
    "  if (flags & F_DEBUG_VERTEX) return float4(d.rgb, 1.0);\n"
    "  if (flags & F_DEBUG_DEPTH) return float4(i.pos.zzz, 1.0);\n"
    "  if (flags & F_DEBUG_TEXTURE)\n"
    "    return (tf & F_TEXTURED) ? float4(sample_world(i.layer, i.uv, gx, gy).rgb, 1.0) : float4(1.0, 0.0, 1.0, 1.0);\n"
    "  if (tf & F_TEXTURED) {\n"
    "    float4 t = sample_world(i.layer, i.uv, gx, gy);\n"
    "    if ((tf & F_KEY_TEST) && t.a < 0.5) discard;\n"
    "    if (!(tf & F_TEX_ALPHA)) t.a = 1.0;\n"
    "    bool lsb = ((uint)round(t.a * 255.0) & 1u) != 0;\n"
    "    if (blend_mode == 1 || blend_mode == 7) c = t;\n"
    "    else if (blend_mode == 3) c = float4(lerp(d.rgb, t.rgb, t.a), d.a);\n"
    "    else if (blend_mode == 4) c = t * d;\n"
    "    else if (blend_mode == 5) c = float4(lsb ? t.rgb : d.rgb, d.a);\n"
    "    else if (blend_mode == 6) c = float4(lsb ? t.rgb * d.rgb : d.rgb, d.a);\n"
    "    else if (blend_mode == 8) c = float4(saturate(t.rgb + d.rgb), d.a);\n"
    "    else if (blend_mode == 16) c = float4(saturate(2.0 * t.rgb * d.rgb), t.a * d.a);\n"
    "    else c = float4(t.rgb * d.rgb, (tf & F_TEX_ALPHA) ? t.a : d.a);\n"
    "  }\n"
    "  if (flags & F_SPECULAR) c.rgb += s;\n"
    "  if ((flags & F_ALPHA_TEST) && !alpha_pass(c.a)) discard;\n"
    "  if (flags & F_FOG) c.rgb = lerp(fog_color.rgb, c.rgb, saturate(fog));\n"
    "  return saturate(c);\n"
    "}\n"
    "float4 ps_fixed(PSIn i) : SV_Target { return fixed_color(i, i.specular.a); }\n"
    /* With ambient occlusion on, the target's alpha is the share of the pixel the fog leaves visible. The coverage is
     * the second blend source, so a blended draw mixes colour and visibility alike. */
    "struct AoOut { float4 color : SV_Target0; float4 cover : SV_Target1; };\n"
    "float ao_visibility(float fog) {\n"
    "  return (flags & F_AO_CLOSED) ? 0.0 : (flags & F_FOG) ? saturate(fog) : 1.0;\n"
    "}\n"
    "AoOut ao_out(float4 c, float visibility) {\n"
    "  AoOut o;\n"
    "  o.color = float4(c.rgb, visibility);\n"
    "  o.cover = c.aaaa;\n"
    "  return o;\n"
    "}\n"
    "AoOut ps_fixed_ao(PSIn i) {\n"
    "  float4 c = fixed_color(i, i.specular.a);\n"
    "  return ao_out(c, ao_visibility(i.specular.a));\n"
    "}\n"
    /* The scene behind the water, displaced by the wave heights' differences under this texel, under the water's own
     * colour at its own alpha. */
    "float4 water_behind(PSIn i) {\n"
    "  float2 waves = water_waves.Sample(samp_linear, i.uv).rg;\n"
    "  float2 shift = waves * fx_water.z * saturate(i.rhw * fx_water2.x) * float2(fx_water.w, 1.0);\n"
    "  float2 base = i.pos.xy * fx_water.xy;\n"
    "  float2 room = float2(shift.x > 0.0 ? (fx_water3.z - base.x) / shift.x : shift.x < 0.0 ? (fx_water3.x - base.x) / shift.x : 1.0,\n"
    "                       shift.y > 0.0 ? (fx_water3.w - base.y) / shift.y : shift.y < 0.0 ? (fx_water3.y - base.y) / shift.y : 1.0);\n"
    "  return scene_behind.Sample(samp_linear, base + shift * saturate(min(room.x, room.y)));\n"
    "}\n"
    "float4 ps_water(PSIn i) : SV_Target {\n"
    "  float4 c = fixed_color(i, i.specular.a);\n"
    "  return float4(lerp(water_behind(i).rgb, c.rgb, c.a), 1.0);\n"
    "}\n"
    "AoOut ps_water_ao(PSIn i) {\n"
    "  float4 c = fixed_color(i, i.specular.a), behind = water_behind(i);\n"
    "  return ao_out(float4(lerp(behind.rgb, c.rgb, c.a), 1.0), lerp(behind.a, ao_visibility(i.specular.a), c.a));\n"
    "}\n"
    /* The sky's fog from the view direction (fx_sky_fog), in place of the retail per-vertex depth fog. */
    "float sky_fog(PSIn i) {\n"
    "  float2 d = i.uv - fx_sky.xy;\n"
    "  float all = sqrt(dot(d, d) + fx_sky.z * fx_sky.z);\n"
    "  float v = all > 0.0 ? sqrt(dot(d, d)) / all : 0.0;\n"
    "  float f = v <= fx_sky.w ? 0.0 : v >= fx_sky2.x ? 1.0 : (v - fx_sky.w) / (fx_sky2.x - fx_sky.w);\n"
    "  return 1.0 - f;\n"
    "}\n"
    "float4 ps_sky(PSIn i) : SV_Target { return fixed_color(i, sky_fog(i)); }\n"
    "AoOut ps_sky_ao(PSIn i) {\n"
    "  float fog = sky_fog(i);\n"
    "  float4 c = fixed_color(i, fog);\n"
    "  return ao_out(c, ao_visibility(fog));\n"
    "}\n"
    /* A normal-mapped polygon of a custom level (jpt_lit.h): its vertex colours are those of no and of full reflectance. */
    "struct VSLitIn { float4 pos : POSITION; float4 diffuse : COLOR0; float4 specular : COLOR1; float2 uv : TEXCOORD0; uint layer : TEXCOORD1;\n"
    "                 float4 light : TEXCOORD2; float4 material : TEXCOORD3; float2 shade : TEXCOORD4; uint normal : TEXCOORD5; };\n"
    "struct PSLit {\n"
    "  float4 pos : SV_Position;\n"
    "  float4 dark : COLOR0;\n"
    "  float4 full : COLOR1;\n"
    "  float2 uv : TEXCOORD0;\n"
    "  nointerpolation uint layer : TEXCOORD1;\n"
    "  float4 light : TEXCOORD2;\n"
    "  nointerpolation float4 material : TEXCOORD3;\n"
    "  nointerpolation float2 shade : TEXCOORD4;\n"
    "  nointerpolation uint normal : TEXCOORD5;\n"
    "};\n"
    "PSLit vs_lit(VSLitIn v) {\n"
    "  PSLit o;\n"
    "  float w = v.pos.w > 1e-20 ? 1.0 / v.pos.w : 1.0;\n"
    "  float2 ndc = float2((v.pos.x + 0.5) * target.z * 2.0 - 1.0, 1.0 - (v.pos.y + 0.5) * target.w * 2.0);\n"
    "  o.pos = float4(ndc * w, saturate(v.pos.z) * w, w);\n"
    "  o.dark = v.diffuse; o.full = v.specular; o.uv = v.uv; o.layer = v.layer;\n"
    "  o.light = v.light; o.material = v.material; o.shade = v.shade; o.normal = v.normal;\n"
    "  return o;\n"
    "}\n"
    "float4 lit_color(PSLit i) {\n"
    "  uint tf = (i.layer >> 20) & 7u;\n"
    "  float2 gx = ddx(i.uv), gy = ddy(i.uv);\n"
    "  float4 t = sample_world(i.layer, i.uv, gx, gy), m = sample_world(i.normal, i.uv, gx, gy);\n"
    "  float begins = i.material.z * 0.998749197, len = length(i.light.xyz);\n"
    "  float light = len > 1e-6 ? dot(m.rgb * 2.0 - 1.0, i.light.xyz / len) : 0.0;\n"
    "  float value, shown;\n"
    "  float3 over = 0.0;\n"
    "  float4 c;\n"
    "  if ((tf & F_KEY_TEST) && t.a < 0.5) discard;\n"
    "  light = (light >= 0.0 ? light * i.light.w : 0.0) + i.material.w;\n"
    "  value = light * i.material.x;\n"
    "  if (i.material.y > 0.0) value = lerp(value, i.material.y, saturate((light - begins) / (0.998749197 - begins)) * m.a);\n"
    "  shown = max(value >= 1.0 ? 1.0 : pow(max(value, 0.0), i.shade.x), i.shade.y);\n"
    "  if (i.material.y > 0.0 && value >= 1.0) over = (value - 1.0) * i.full.rgb;\n"
    "  c.rgb = lerp(over, lerp(i.dark.rgb, i.full.rgb, shown), t.rgb);\n"
    "  c.a = (tf & F_TEX_ALPHA) ? t.a : i.dark.a;\n"
    "  if ((flags & F_ALPHA_TEST) && !alpha_pass(c.a)) discard;\n"
    "  if (flags & F_FOG) c.rgb = lerp(fog_color.rgb, c.rgb, saturate(i.full.a));\n"
    "  return saturate(c);\n"
    "}\n"
    "float4 ps_lit(PSLit i) : SV_Target { return lit_color(i); }\n"
    "AoOut ps_lit_ao(PSLit i) {\n"
    "  float4 c = lit_color(i);\n"
    "  return ao_out(c, ao_visibility(i.full.a));\n"
    "}\n"
    /* Rectangle passes: clears, the legacy picture, overlays and presentation, from pass_rect in NDC. */
    "struct QuadOut { float4 pos : SV_Position; float2 uv : TEXCOORD0; };\n"
    "QuadOut vs_quad(uint id : SV_VertexID) {\n"
    "  QuadOut o;\n"
    "  float2 k = float2(id & 1, id >> 1);\n"
    "  o.pos = float4(lerp(pass_rect.xy, pass_rect.zw, k), pass_depth, 1.0);\n"
    "  o.uv = lerp(pass_uv.xy, pass_uv.zw, k);\n"
    "  return o;\n"
    "}\n"
    "float4 ps_fill(QuadOut i) : SV_Target { return pass_color; }\n"
    "float4 ps_copy(QuadOut i) : SV_Target { return tex0.Sample(samp0, i.uv); }\n"
    /* ps_copy for CPU pixels while ambient occlusion marks them in the stencil: unwritten texels leave no mark. */
    "float4 ps_copy_cpu(QuadOut i) : SV_Target {\n"
    "  float4 c = tex0.Sample(samp0, i.uv);\n"
    "  if (c.a < 0.5) discard;\n"
    "  return c;\n"
    "}\n"
    /* The CPU copy's own RGB565 pixels inside pass_uv (pass_color.xy = the copy's size); unwritten ones (0xF81F) are
     * left alone and leave no stencil mark. */
    "Texture2D<uint> cpu_raw : register(t20);\n"
    "float4 ps_copy_raw(QuadOut i) : SV_Target {\n"
    "  float2 lo = pass_uv.xy * pass_color.xy, hi = pass_uv.zw * pass_color.xy - 1.0;\n"
    "  int2 p = (int2)clamp(floor(i.uv * pass_color.xy), lo, hi);\n"
    "  uint v = cpu_raw.Load(int3(p, 0));\n"
    "  if (v == 0xF81Fu) discard;\n"
    "  uint3 c = uint3(v >> 11, (v >> 5) & 63u, v & 31u);\n"
    "  c = uint3((c.r << 3) | (c.r >> 2), (c.g << 2) | (c.g >> 4), (c.b << 3) | (c.b >> 2));\n"
    "  return float4(c / 255.0, 1.0);\n"
    "}\n"
    /* The perspective-textured software primitive on the GPU (texture_gpu_policy.h): the polygon's fan from poly_xy in
     * the surface's pixels; per pixel u/z, v/z, 1/z from their planes, the texel index as the span walks it, an 8-bit
     * texel and its CLUT pixel. */
    "cbuffer Poly : register(b4) {\n"
    "  float4 poly_xy[32]; float4 poly_u; float4 poly_v; float4 poly_w;\n"
    "  float4 poly_origin; float4 poly_size; float4 poly_clamp; uint4 poly_tex; uint4 poly_lut; uint4 poly_bump;\n"
    "};\n"
    "Buffer<uint> poly_texels : register(t21);\n"
    "Buffer<uint> poly_clut : register(t22);\n"
    "Buffer<uint> poly_bump_clut : register(t23);\n"
    "Buffer<uint> poly_bump_table : register(t24);\n"
    "float4 vs_poly(uint id : SV_VertexID) : SV_Position {\n"
    "  uint tri = id / 3u, corner = id - tri * 3u;\n"
    "  uint k = corner == 0u ? 0u : tri + corner;\n"
    "  float4 pair = poly_xy[k >> 1];\n"
    "  float2 p = (k & 1u) ? pair.zw : pair.xy;\n"
    "  return float4(p.x / poly_size.x * 2.0 - 1.0, 1.0 - p.y / poly_size.y * 2.0, 0.0, 1.0);\n"
    "}\n"
    "uint poly_index(float4 pos) {\n"
    "  float2 q = floor(pos.xy * poly_size.zw) - poly_origin.xy;\n"
    "  float w = poly_w.x + poly_w.y * q.x + poly_w.z * q.y;\n"
    "  float u = (poly_u.x + poly_u.y * q.x + poly_u.z * q.y) / w;\n"
    "  float v = (poly_v.x + poly_v.y * q.x + poly_v.z * q.y) / w;\n"
    "  bool clamped = poly_clamp.w != 0.0;\n"
    "  if (clamped) { u = clamp(u, poly_clamp.x, poly_clamp.y); v = clamp(v, poly_clamp.x, poly_clamp.z); }\n"
    "  int iu = (int)floor(u), iv = (int)floor(v);\n"
    "  uint row = clamped ? (uint)iv * poly_tex.y : (uint)iv << 9;\n"
    "  return (row + ((uint)iu & poly_tex.z)) & poly_tex.w;\n"
    "}\n"
    "float4 poly_color(uint pixel) {\n"
    "  uint3 c = uint3(pixel >> 11, (pixel >> 5) & 63u, pixel & 31u);\n"
    "  c = uint3((c.r << 3) | (c.r >> 2), (c.g << 2) | (c.g >> 4), (c.b << 3) | (c.b >> 2));\n"
    "  return float4(c / 255.0, 1.0);\n"
    "}\n"
    "float4 ps_poly_texture(float4 pos : SV_Position) : SV_Target {\n"
    "  return poly_color(poly_clut[poly_lut.x + poly_texels[poly_tex.x + poly_index(pos)]]);\n"
    "}\n"
    /* The bump-mapped perspective primitive (SelfMod 0x006402F0): a 16-bit texel (two bytes of the texel buffer) is an
     * angle into the intensity table and a row of the CLUT. */
    "float4 ps_poly_bump(float4 pos : SV_Position) : SV_Target {\n"
    "  uint at = poly_tex.x + poly_index(pos) * 2u;\n"
    "  uint texel = poly_texels[at] | (poly_texels[at + 1u] << 8);\n"
    "  uint intensity = poly_bump_table[poly_bump.x + ((texel - poly_bump.y) & 0x3FFu)];\n"
    "  return poly_color(poly_bump_clut[poly_bump.z + intensity * 64u + (texel >> 10)]);\n"
    "}\n"
    /* Readback in the surface's own format, rounded as d3dt_bgra_to_rgb565 does. */
    "uint ps_pack565(QuadOut i) : SV_Target {\n"
    "  uint3 k = (uint3)(saturate(tex0.Sample(samp0, i.uv).rgb) * 255.0 + 0.5);\n"
    "  uint3 q = (k * uint3(31, 63, 31) + 127) / 255;\n"
    "  return (q.r << 11) | (q.g << 5) | q.b;\n"
    "}\n"
    "float4 ps_present(QuadOut i) : SV_Target {\n"
    "  float4 c = saturate(tex0.Sample(samp0, i.uv));\n"
    "  int3 k = int3(round(c.rgb * 255.0));\n"
    "  return float4(gamma_lut.Load(int3(k.r, 0, 0)).r, gamma_lut.Load(int3(k.g, 0, 0)).g,\n"
    "                gamma_lut.Load(int3(k.b, 0, 0)).b, c.a);\n"
    "}\n";

