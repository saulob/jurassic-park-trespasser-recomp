#include "jpt_lift_meta.h"

#include <string.h>

static int same(const char* a, const char* b) { return a && b && !strcmp(a, b); }

jpt_lift_meta_result_t jpt_lift_meta_check(const jpt_lift_meta_t* expected, const jpt_lift_meta_t* actual) {
    if (!expected || !actual) return JPT_LIFT_META_MISSING;
    if (!same(expected->lift_id, actual->lift_id)) return JPT_LIFT_META_WRONG_LIFT;
    if (!same(expected->source_profile, actual->source_profile)) return JPT_LIFT_META_WRONG_PROFILE;
    if (!same(expected->source_sha256, actual->source_sha256)) return JPT_LIFT_META_WRONG_EXECUTABLE;
    if (expected->format != actual->format) return JPT_LIFT_META_WRONG_FORMAT;
    if (actual->image_base != JPT_GUEST_IMAGE_BASE || expected->image_base != actual->image_base ||
        expected->entry_va != actual->entry_va || expected->selfmod_start != actual->selfmod_start)
        return JPT_LIFT_META_WRONG_IMAGE;
    if (!actual->function_count) return JPT_LIFT_META_EMPTY;
    return JPT_LIFT_META_OK;
}

const char* jpt_lift_meta_result_text(jpt_lift_meta_result_t result) {
    switch (result) {
    case JPT_LIFT_META_OK: return "ok";
    case JPT_LIFT_META_MISSING: return "no lift metadata";
    case JPT_LIFT_META_WRONG_LIFT: return "another lift";
    case JPT_LIFT_META_WRONG_PROFILE: return "generated from another profile";
    case JPT_LIFT_META_WRONG_EXECUTABLE: return "generated from another executable";
    case JPT_LIFT_META_WRONG_FORMAT: return "generated by another version of the lift tool";
    case JPT_LIFT_META_WRONG_IMAGE: return "another guest image layout";
    default: return "no lifted functions";
    }
}
