#!/usr/bin/env python3
"""Writes the header that gives the Linux executable its provenance (src/linux/linux_selfcheck.c reads it).

    python3 -I tools/gen_build_info.py --out FILE --version V --compiler TEXT --target TEXT --config NAME

The file is rewritten only when its text changes, so an unchanged tree recompiles nothing. No clock: the same sources give the same
header; the time of a gate run lives in the build manifest next to the executable (tools/linux_artifact.py)."""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import source_fingerprint  # noqa: E402


def git(*args):
    try:
        done = subprocess.run(["git", "-c", "safe.directory=*", "-C", str(ROOT), *args], stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, timeout=60)
        return done.stdout.decode("utf-8", "replace").strip() if done.returncode == 0 else None
    except (OSError, subprocess.SubprocessError):
        return None


def contract_facts():
    path = ROOT / "tests" / "feature_contract.json"
    data = path.read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest(), json.loads(data.decode("utf-8")).get("schema", 0)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", required=True)
    parser.add_argument("--version", default="0")
    parser.add_argument("--compiler", default="unknown")
    parser.add_argument("--target", default="linux-x86_64")
    parser.add_argument("--config", default="unknown")
    args = parser.parse_args()
    commit = git("rev-parse", "HEAD") or "unknown"
    status = git("status", "--porcelain")
    dirty = 1 if status is None or status else 0
    contract_sha, contract_schema = contract_facts()
    fields = {
        "VERSION": args.version,
        "GIT_COMMIT": commit,
        "SOURCE_FINGERPRINT": source_fingerprint.fingerprint(ROOT),
        "COMPILER": args.compiler,
        "TARGET": args.target,
        "CONFIG": args.config,
        "GLIBC_BASELINE": "2.31",
        "CONTRACT_SHA256": contract_sha,
    }
    lines = ["/* Generated by tools/gen_build_info.py: do not edit. */", "#ifndef JPT_BUILD_INFO_H", "#define JPT_BUILD_INFO_H"]
    lines += ['#define JPT_BUILD_%s "%s"' % (key, value.replace("\\", "\\\\").replace('"', '\\"')) for key, value in fields.items()]
    lines += ["#define JPT_BUILD_GIT_DIRTY %d" % dirty, "#define JPT_BUILD_CONTRACT_SCHEMA %d" % contract_schema, "#endif", ""]
    text = "\n".join(lines)
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    if not out.exists() or out.read_text(encoding="utf-8") != text:
        with open(out, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
