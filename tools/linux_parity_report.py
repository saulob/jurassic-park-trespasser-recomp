#!/usr/bin/env python3
"""The Windows / Linux feature inventory (docs/LINUX_PARITY.md), written from tests/feature_contract.json.

    python3 -I tools/linux_parity_report.py --write    # rewrite docs/LINUX_PARITY.md
    python3 -I tools/linux_parity_report.py --check    # exit 1 when the file is not what the contract produces
    python3 -I tools/linux_parity_report.py --summary  # counts only

The contract is the machine-readable matrix: every feature has a Windows status, a Linux status, the suites that prove each and a
reason when the two differ. The gate (tools/test.ps1, tools/test-linux.sh) fails a global feature that is not PASS on both and
a status other than PASS that has no reason; this file only presents it."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "tests" / "feature_contract.json"
OUT = ROOT / "docs" / "LINUX_PARITY.md"


def label(feature, platform):
    section = feature[platform]
    status = section["status"]
    if status == "PASS":
        return "PASS"
    if status == "PLATFORM_ONLY":
        return "WINDOWS ONLY (justified)" if platform == "linux" else "LINUX ONLY (justified)"
    return "MISSING (blocked)"


def suites(feature, platform):
    names = []
    for item in feature.get("shared", []) + feature[platform].get("evidence", []):
        suite = item["suite"].replace("tests\\", "").replace("\\", "/")
        if suite not in names:
            names.append(suite)
    return ", ".join(f"`{n}`" for n in names) or "-"


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ")


def render(contract):
    features = contract["features"]
    counts = {}
    for feature in features:
        key = (label(feature, "windows"), label(feature, "linux"))
        counts[key] = counts.get(key, 0) + 1
    lines = [
        "# Windows / Linux feature inventory",
        "",
        "Generated by `tools/linux_parity_report.py` from `tests/feature_contract.json`; do not edit by hand. The contract is the",
        "machine-readable matrix: each feature has a status per platform, the suites that prove it and a reason when the platforms",
        "differ. `tools/test.ps1` and `tools/test-linux.sh` fail a global feature that is not PASS on both platforms, a status",
        "other than PASS that has no reason, and a suite or evidence pattern that no longer exists.",
        "",
        "Statuses: **PASS** is proved by suites that exist and passed in the run. **WINDOWS ONLY (justified)** and **LINUX ONLY",
        "(justified)** name a platform-specific implementation and say why. **MISSING (blocked)** is a gap with a reason; no global",
        "feature may have one.",
        "",
        f"{len(features)} features. " + "; ".join(f"{n} {w} / {l}" for (w, l), n in sorted(counts.items(), key=lambda kv: -kv[1])) + ".",
        "",
        "| Feature | Scope | Windows | Linux | Windows evidence | Linux evidence | Justification |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for feature in features:
        reason = " ".join(feature[p].get("reason", "") for p in ("windows", "linux")).strip()
        lines.append("| " + " | ".join(cell(x) for x in (
            f"`{feature['id']}`", feature["scope"], label(feature, "windows"), label(feature, "linux"),
            suites(feature, "windows"), suites(feature, "linux"), reason or "-")) + " |")
    lines.append("")
    return "\n".join(lines)


def main():
    contract = json.loads(CONTRACT.read_bytes().replace(b"\r\n", b"\n").decode("utf-8"))
    text = render(contract)
    mode = sys.argv[1] if len(sys.argv) > 1 else "--check"
    if mode == "--write":
        OUT.write_text(text, encoding="utf-8", newline="\n")
        print(f"{OUT.relative_to(ROOT)}: {len(contract['features'])} features")
        return 0
    if mode == "--summary":
        print(text.split("\n\n")[5])
        return 0
    current = OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") if OUT.is_file() else ""
    if current != text:
        print("docs/LINUX_PARITY.md is not what tests/feature_contract.json produces: run python3 -I tools/linux_parity_report.py --write")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
