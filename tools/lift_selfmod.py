#!/usr/bin/env python3
"""Lifts the SelfMod section (the rasteriser's inner loops) to C with the same lifter as .text.

SelfMod routines patch the trailing dword of 44 of their own instructions in their prologues (a texture base, a colour
table base); the lifter reads those fields from guest memory (Lifter patch_sites), so the generated C performs the
patch as an ordinary guest store and the loop reads it back. No guest byte is ever executed.

Output: recomp_selfmod.c in the lift's generated folder: the lifted routines and <lift>_selfmod_dispatch_table, which
lists every entry (routine starts and the stubs the section's data and atexit registrations point at).

    py -3 tools/lift_selfmod.py                    # lift the baseline build into src/recomp/gen
    py -3 tools/lift_selfmod.py --check            # verify the committed recomp_selfmod.c against the executable
tools/run_lift.py calls emit() for every lift it generates.
"""
import argparse
import re
import sys
from pathlib import Path

from common import GEN_DIR, LIFT_PREFIX, TARGET, decoder_fixups, require_target_exe, use_pcrecomp

use_pcrecomp("lift", "pe")

from capstone import Cs, CS_ARCH_X86, CS_MODE_32           # noqa: E402
from generate import (EXTENT_REACH, linear_disassemble_function, lift_function_linear, true_extent)  # noqa: E402
from lift32 import Lifter                                    # noqa: E402
from pe_analyze import analyze_pe, build_iat_map             # noqa: E402

import x64_selfmod_scan as scan                              # noqa: E402

BANNER = "/* Trespasser - AUTO-GENERATED by tools/lift_selfmod.py - derived from the retail binary, do not commit */\n"
NAME = "recomp_selfmod.c"
LIFTED_NAME = re.compile(r"\bsub_([0-9A-F]{8})\b")
CALL_TARGET = re.compile(r"RECOMP_(?:ICALL|ITAIL|CALL)\(0x([0-9A-F]{8})u\)")


def prefixed(body):
    return LIFTED_NAME.sub(lambda m: LIFT_PREFIX + m.group(0), body)


def selfmod_range(info):
    sm = {s.name: s for s in info.sections}["SelfMod"]
    base = info.image_base
    return sm, base + sm.virtual_address, base + sm.virtual_address + sm.virtual_size


def main_entries(gen_dir):
    """The lifted .text entries of the lift in gen_dir, read from its dispatch table."""
    text = (Path(gen_dir) / "recomp_dispatch.c").read_text(encoding="utf-8")
    return {int(m.group(1), 16) for m in re.finditer(r"\{ 0x([0-9A-F]{8})u,", text)}


def referenced_targets(gen_dir, lo, hi):
    """Constant call and jump targets inside [lo, hi) that the lifted .text uses."""
    found = set()
    for path in sorted(Path(gen_dir).glob("recomp_0*.c")):
        for m in CALL_TARGET.finditer(path.read_text(encoding="utf-8", errors="replace")):
            target = int(m.group(1), 16)
            if lo <= target < hi:
                found.add(target)
    return found


def decodable(raw, start):
    """The section bytes with each undecodable encoding of config/decoder_fixups.json swapped for its canonical twin."""
    code = bytearray(raw)
    for fix in decoder_fixups():
        off = int(fix["va"], 16) - start
        if not 0 <= off < len(code):
            continue
        expect, decode_as = bytes.fromhex(fix["expect"]), bytes.fromhex(fix["decode_as"])
        if bytes(code[off:off + len(expect)]) != expect:
            sys.exit(f"decoder fixup at {fix['va']} does not match this binary")
        code[off:off + len(expect)] = decode_as
    return bytes(code)


def lift(exe_bytes, info, text_entries, referenced):
    """Returns (C source, entries, report) for the SelfMod section of the executable."""
    sm, lo, hi = selfmod_range(info)
    data = decodable(exe_bytes[sm.raw_offset:sm.raw_offset + sm.virtual_size], lo)
    routines, abs_writes = scan.analyse(data, lo, hi)
    if abs_writes:
        sys.exit(f"SelfMod is written through absolute addresses at {[hex(a) for a in abs_writes]}: not modelled")
    starts = {r["entry"] for r in routines}
    patches = [p for r in routines for p in r["patches"]]
    untrailing = [p for p in patches if not p["trailing"]]
    if untrailing:
        sys.exit(f"{len(untrailing)} patch sites are not the trailing dword of their instruction: not modelled")
    sites = {p["site"] for p in patches}
    missing = sorted(referenced - starts)
    if missing:
        sys.exit("lifted code enters SelfMod at addresses that are not routine starts: " + ", ".join(f"0x{a:08X}" for a in missing))

    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    lifter = Lifter(iat_map=build_iat_map(info), lifted=set(text_entries) | starts, precise_carry=True,
                    precise_sbb=True, patch_sites=sites)
    bodies, errors, outside = [], [], set()
    for addr in sorted(starts):
        reached, behind, called = set(), set(), set()
        end, _ = true_extent(md, data, lo, addr, min(addr + EXTENT_REACH, hi), starts, reached=reached,
                             behind=behind, called=called)
        outside |= {t for t in called if not lo <= t < hi}
        outside |= {t for t in behind if t not in reached and not lo <= t < hi}
        first = min(reached) if reached else addr
        insns, leaders = linear_disassemble_function(md, data, lo, first, end, reached=reached)
        leaders.add(addr)
        try:
            if not insns:
                raise ValueError("no instructions decoded")
            body = lift_function_linear(lifter, f"sub_{addr:08X}", insns, leaders, addr)
        except Exception as exc:  # noqa: BLE001 -- reported, never hidden
            errors.append(f"0x{addr:08X}: {exc}")
            continue
        bodies.append((addr, prefixed(body)))
    unknown = sorted(t for t in outside if t not in text_entries)
    if unknown:
        errors.append("calls or jumps out of SelfMod to addresses with no lifted entry: " + ", ".join(f"0x{t:08X}" for t in unknown))
    if errors:
        sys.exit("SelfMod did not lift:\n  " + "\n  ".join(errors))

    names = {a: f"{LIFT_PREFIX}sub_{a:08X}" for a, _ in bodies}
    out = [BANNER, "#define RECOMP_GENERATED_CODE\n", '#include "recomp_types.h"\n', '#include "recomp_funcs.h"\n',
           "#include <math.h>\n#include <string.h>\n\n"]
    out += [f"void {names[a]}(void);\n" for a, _ in bodies]
    out.append("\n")
    for _, body in bodies:
        out += [body, "\n\n"]
    out.append(f"const recomp_dispatch_entry_t {LIFT_PREFIX}selfmod_dispatch_table[] = {{\n")
    out += [f"    {{ 0x{a:08X}u, {names[a]} }},\n" for a, _ in bodies]
    out.append("};\n")
    out.append(f"const unsigned {LIFT_PREFIX}selfmod_dispatch_count = {len(bodies)}u;\n")
    report = {"entries": len(bodies), "patch_sites": len(sites), "calls_out": sorted(outside), "range": (lo, hi)}
    return "".join(out), sorted(names), report


def emit(out_dir, exe, info, text_entries, gen_dir=None):
    """Writes recomp_selfmod.c into out_dir. text_entries: the lifted .text addresses of this lift."""
    _, lo, hi = selfmod_range(info)
    source, _, report = lift(Path(exe).read_bytes(), info, text_entries,
                             referenced_targets(gen_dir or out_dir, lo, hi))
    Path(out_dir, NAME).write_text(source, encoding="utf-8", newline="\n")
    return report


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gen-dir", type=Path, default=GEN_DIR)
    ap.add_argument("--check", action="store_true", help="compare with the file in --gen-dir instead of writing it")
    args = ap.parse_args()
    exe = require_target_exe()
    info = analyze_pe(str(exe))
    _, lo, hi = selfmod_range(info)
    if lo != int(TARGET["selfmod"]["start"], 16):
        sys.exit("SelfMod is not where config/target.json says it is")
    source, names, report = lift(exe.read_bytes(), info, main_entries(args.gen_dir),
                                 referenced_targets(args.gen_dir, lo, hi))
    target = args.gen_dir / NAME
    print(f"SelfMod 0x{lo:08X}-0x{hi:08X}: {report['entries']} entries, {report['patch_sites']} patch sites, "
          f"calls out to {[hex(a) for a in report['calls_out']]}")
    if args.check:
        same = target.exists() and target.read_text(encoding="utf-8") == source
        print("recomp_selfmod.c matches the executable" if same else "recomp_selfmod.c differs or is missing")
        return 0 if same else 1
    target.write_text(source, encoding="utf-8", newline="\n")
    print(f"wrote {target} ({len(source.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
