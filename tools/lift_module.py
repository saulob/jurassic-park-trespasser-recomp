#!/usr/bin/env python3
"""Lifts the guest DLLs listed in config/guest_modules.json to C with the lifter used for the executable.

A guest DLL is a development input: it is read here, checked against its recorded SHA-256, and never executed. The output is
recomp_<module>.c (every lifted function, <prefix>dispatch_table, <prefix>meta) and recomp_<module>.json (the facts the manifest
records) in the lift's generated folder. The lifted code assumes the DLL's preferred base (absolute addresses are baked in).

    py -3 tools/lift_module.py                      # lift every listed module into src/recomp/gen
    py -3 tools/lift_module.py --check              # compare the committed output with the DLL
tools/run_lift.py calls emit() for every lift that lists the modules.
"""
import argparse
import hashlib
import json
import os
import re
import struct
import sys
from pathlib import Path

from common import CONFIG_DIR, GEN_DIR, LIFT_ID, decoder_fixups, use_pcrecomp

use_pcrecomp("lift", "pe")

from capstone import Cs, CS_ARCH_X86, CS_MODE_32           # noqa: E402
from generate import EXTENT_REACH, linear_disassemble_function, lift_function_linear, true_extent  # noqa: E402
from lift32 import Lifter                                    # noqa: E402
from pe_analyze import analyze_pe, build_iat_map             # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
BANNER = "/* Trespasser - AUTO-GENERATED by tools/lift_module.py - derived from a retail DLL, do not commit */\n"
SUB_NAME = re.compile(r"\bsub_([0-9A-F]{8})\b")
HIGHLOW = 3


def modules_config():
    return json.loads((CONFIG_DIR / "guest_modules.json").read_text(encoding="utf-8"))["modules"]


def find_module_file(cfg):
    names = [os.environ.get("JPT_MODULE_" + cfg["file"].split(".")[0].upper())]
    names += [ROOT / "game" / "versions" / "en-116" / cfg["file"], ROOT / "game" / cfg["file"]]
    for candidate in names:
        if candidate and Path(candidate).is_file():
            return Path(candidate)
    sys.exit(f"{cfg['file']} is a development input of the lift: install the game, or point JPT_MODULE_"
             f"{cfg['file'].split('.')[0].upper()} at it")


def u32(data, off):
    return struct.unpack_from("<I", data, off)[0]


class Image:
    """The DLL as the loader lays it out at its preferred base, read with the standard library only."""

    def __init__(self, raw, info):
        self.raw, self.info, self.base = raw, info, info.image_base
        self.size = u32(raw, u32(raw, 0x3C) + 24 + 56)
        self.mem = bytearray(self.size)
        self.mem[:u32(raw, u32(raw, 0x3C) + 24 + 60)] = raw[:u32(raw, u32(raw, 0x3C) + 24 + 60)]
        for s in info.sections:
            n = min(s.raw_size, s.virtual_size or s.raw_size)
            self.mem[s.virtual_address:s.virtual_address + n] = raw[s.raw_offset:s.raw_offset + n]
        pe = u32(raw, 0x3C)
        self.relocs = self._relocations(u32(raw, pe + 24 + 96 + 8 * 5), u32(raw, pe + 24 + 96 + 8 * 5 + 4))
        self.tls = u32(raw, pe + 24 + 96 + 8 * 9)

    def section(self, name):
        return next(s for s in self.info.sections if s.name.rstrip("\0") == name)

    def _relocations(self, rva, size):
        out, off = [], rva
        while rva and off < rva + size:
            page, block = u32(self.mem, off), u32(self.mem, off + 4)
            if block < 8:
                break
            for i in range((block - 8) // 2):
                entry, = struct.unpack_from("<H", self.mem, off + 8 + 2 * i)
                if entry >> 12 == HIGHLOW:
                    out.append(page + (entry & 0xFFF))
            off += block
        return out

    def exports(self):
        pe = u32(self.raw, 0x3C)
        rva = u32(self.raw, pe + 24 + 96)
        d = rva
        base_ord, nfuncs, nnames = u32(self.mem, d + 16), u32(self.mem, d + 20), u32(self.mem, d + 24)
        funcs, names, ords = u32(self.mem, d + 28), u32(self.mem, d + 32), u32(self.mem, d + 36)
        out = []
        for i in range(nnames):
            name_rva = u32(self.mem, names + 4 * i)
            end = self.mem.index(b"\0", name_rva)
            ordinal_index, = struct.unpack_from("<H", self.mem, ords + 2 * i)
            out.append((base_ord + ordinal_index, bytes(self.mem[name_rva:end]).decode("latin1"), u32(self.mem, funcs + 4 * ordinal_index)))
        assert len(out) == nfuncs == nnames, "exports without names are not modelled"
        return sorted(out)


def decodable(code, start):
    code = bytearray(code)
    for fix in decoder_fixups():
        off = int(fix["va"], 16) - start
        if 0 <= off < len(code):
            expect, as_ = bytes.fromhex(fix["expect"]), bytes.fromhex(fix["decode_as"])
            if bytes(code[off:off + len(expect)]) != expect:
                sys.exit(f"decoder fixup at {fix['va']} does not match this binary")
            code[off:off + len(expect)] = as_
    return bytes(code)


def discover(md, code, lo, hi, seeds, mid_ok):
    """Function starts: the seeds and every direct call or jump target they reach, to a fixpoint. A seed that sits inside
    another function's body and is never called or jumped to is a label of that body, not a function."""
    seeds = set(seeds)
    while True:
        starts, extents, entered = set(seeds), {}, set()
        while True:
            extents.clear()
            new = set()
            for addr in sorted(starts):
                reached, behind, called = set(), set(), set()
                end, clean = true_extent(md, code, lo, addr, min(addr + EXTENT_REACH, hi), starts, reached=reached,
                                         behind=behind, called=called)
                extents[addr] = (end, clean, reached)
                targets = called | {t for t in behind if t not in reached}
                entered |= targets
                new |= {t for t in targets if lo <= t < hi and t not in starts}
            if not new:
                break
            starts |= new
        labels = {a for a in seeds if a not in mid_ok and a not in entered and any(a != b and a in ext[2] for b, ext in extents.items())}
        if not labels:
            return starts, extents
        seeds -= labels


def lift(cfg, raw, info):
    image = Image(raw, info)
    text = image.section(".text")
    lo = image.base + text.virtual_address
    hi = lo + text.virtual_size
    code = decodable(bytes(image.mem[text.virtual_address:text.virtual_address + text.virtual_size]), lo)
    exports = image.exports()
    export_rvas = {rva for _, _, rva in exports}
    data_sections = [s for s in info.sections if s.name.rstrip("\0") in (".rdata", ".data")]

    def in_text(va):
        return lo <= va < hi

    code_exports = {image.base + rva for rva in export_rvas if in_text(image.base + rva)}
    data_pointers = set()
    for rva in image.relocs:
        if any(s.virtual_address <= rva < s.virtual_address + max(s.virtual_size, s.raw_size) for s in data_sections):
            target = u32(image.mem, rva)
            if in_text(target):
                data_pointers.add(target)
    immediate_pointers = set()
    for rva in image.relocs:
        if text.virtual_address <= rva < text.virtual_address + text.virtual_size:
            target = u32(image.mem, rva)
            if in_text(target):
                immediate_pointers.add(target)
    entry = image.base + info.entry_point_rva
    seeds = code_exports | data_pointers | immediate_pointers | {entry}

    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    starts, extents = discover(md, code, lo, hi, seeds, code_exports | {entry})
    lifter = Lifter(iat_map=build_iat_map(info), lifted=set(starts), precise_carry=True, precise_sbb=True)
    prefix = cfg["prefix"]
    bodies, errors = [], []
    for addr in sorted(starts):
        end, _, reached = extents[addr]
        first = min(reached) if reached else addr
        insns, leaders = linear_disassemble_function(md, code, lo, first, end, reached=reached)
        leaders.add(addr)
        try:
            if not insns:
                raise ValueError("no instructions decoded")
            body = lift_function_linear(lifter, f"sub_{addr:08X}", insns, leaders, addr)
        except Exception as exc:  # noqa: BLE001 -- reported, never hidden
            errors.append(f"0x{addr:08X}: {exc}")
            continue
        bodies.append((addr, SUB_NAME.sub(lambda m: prefix + m.group(0), body)))
    target = re.compile(r"RECOMP_(?:ICALL|ITAIL)\(0x([0-9A-F]{8})u\)")
    for addr, body in bodies:
        for marker in ("UNIMPLEMENTED", "RECOMP_NOT_LIFTED"):
            if marker in body:
                errors.append(f"0x{addr:08X}: {marker} in the lifted body")
        for m in target.finditer(body):
            if int(m.group(1), 16) not in starts:
                errors.append(f"0x{addr:08X}: a jump or call to 0x{m.group(1)}, which is not a lifted entry")
    if errors:
        sys.exit("the module did not lift:\n  " + "\n  ".join(errors[:20]))

    names = {a: f"{prefix}sub_{a:08X}" for a, _ in bodies}
    out = [BANNER, "#define RECOMP_GENERATED_CODE\n", '#include "recomp_types.h"\n', '#include "recomp_funcs.h"\n',
           '#include "jpt_module_meta.h"\n', "#include <math.h>\n#include <string.h>\n\n"]
    out += [f"void {names[a]}(void);\n" for a, _ in bodies]
    out.append("\n")
    for _, body in bodies:
        out += [body, "\n\n"]
    out.append(f"const recomp_dispatch_entry_t {prefix}dispatch_table[] = {{\n")
    out += [f"    {{ 0x{a:08X}u, {names[a]} }},\n" for a, _ in bodies]
    out.append("};\n")
    code_export_count = sum(1 for _, _, rva in exports if in_text(image.base + rva))
    fingerprint = hashlib.sha256("\n".join(f"{o} {n} {r:08X}" for o, n, r in exports).encode()).hexdigest()
    if cfg.get("export_fingerprint") and cfg["export_fingerprint"] != fingerprint:
        sys.exit("the export table differs from config/guest_modules.json")
    entry_text = f"0x{entry:08X}u"
    out.append(f"const jpt_module_meta_t {prefix}meta = {{\n"
               f'    "{cfg["file"].split(".")[0].lower()}", "{cfg["file"]}", "{cfg["sha256"]}", "{fingerprint}",\n'
               f"    0x{image.base:08X}u, 0x{image.size:08X}u, {entry_text}, 0x{lo:08X}u, 0x{hi:08X}u, {len(bodies)}u, {len(exports)}u\n"
               "};\n")
    facts = {"name": cfg["file"].split(".")[0].lower(), "sha256": cfg["sha256"], "image_base": f"0x{image.base:08X}",
             "image_size": f"0x{image.size:08X}", "entry": f"0x{entry:08X}", "text": [f"0x{lo:08X}", f"0x{hi:08X}"],
             "entries": len(bodies), "exports": len(exports), "code_exports": code_export_count,
             "data_exports": len(exports) - code_export_count, "export_fingerprint": fingerprint,
             "data_pointer_seeds": len(data_pointers), "immediate_pointer_seeds": len(immediate_pointers), "relocations": len(image.relocs), "tls": bool(image.tls)}
    return "".join(out), facts


def verify_source(cfg, path, info):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != cfg["sha256"]:
        sys.exit(f"{path} is not the {cfg['file']} this port supports (config/guest_modules.json)")
    if info.image_base != int(cfg["image_base"], 16) or info.timestamp != cfg["timestamp"]:
        sys.exit(f"{path}: image base or timestamp differs from config/guest_modules.json")
    return raw


def emit(out_dir, lift_id=None):
    """Writes recomp_<module>.c and .json into out_dir for every module listed for this lift."""
    facts_all = []
    for name, cfg in modules_config().items():
        if (lift_id or LIFT_ID) not in cfg["lifts"]:
            continue
        path = find_module_file(cfg)
        info = analyze_pe(str(path))
        source, facts = lift(cfg, verify_source(cfg, path, info), info)
        Path(out_dir, f"recomp_{name}.c").write_text(source, encoding="utf-8", newline="\n")
        Path(out_dir, f"recomp_{name}.json").write_text(json.dumps(facts, indent=1) + "\n", encoding="utf-8", newline="\n")
        facts_all.append(facts)
    return facts_all


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--gen-dir", type=Path, default=GEN_DIR)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    for name, cfg in modules_config().items():
        if LIFT_ID not in cfg["lifts"]:
            continue
        path = find_module_file(cfg)
        info = analyze_pe(str(path))
        source, facts = lift(cfg, verify_source(cfg, path, info), info)
        target = args.gen_dir / f"recomp_{name}.c"
        print(f"{name}: {facts['entries']} functions from {facts['code_exports']} code exports, {facts['data_pointer_seeds']} data "
              f"pointers and the call graph; {facts['data_exports']} data exports, {facts['relocations']} relocations")
        if args.check:
            same = target.is_file() and target.read_text(encoding="utf-8") == source
            print(f"{target.name} " + ("matches the DLL" if same else "differs or is missing"))
            return 0 if same else 1
        target.write_text(source, encoding="utf-8", newline="\n")
        (args.gen_dir / f"recomp_{name}.json").write_text(json.dumps(facts, indent=1) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {target} ({len(source.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
