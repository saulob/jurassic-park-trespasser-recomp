#!/usr/bin/env python3
"""Regenerate src/host/minimap_bounds.inc: the minimap's world bounds per retail level.

The levels are the eight campaign levels, the two test scenes in the retail data folder and the demo's level in its own.
The bounds are the world-space extents of the level's playable objects (its `.region` placements, through
tools/scn_triggers.py's GROFF parser) plus a 5% margin of the larger span, rounded to whole metres. Ocean planes,
the sky backdrop, triggers, teleports, magnets, occlusion volumes, lights, water, particles, actors, guns and the
game's own settings are not part of the playable level and do not stretch the map. North is +Y, east +X; world units
are metres.

    py -3 tools/minimap_bounds.py [--data game/data]
"""
import argparse
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from scn_triggers import Groff, analyse_level

ROOT = Path(__file__).resolve().parent.parent
LEVELS = ["be", "jr", "ij", "it", "lab", "as", "as2", "sum", "testscene", "testscnnght", "demo"]
LEVEL_DIRS = {"demo": ("demo-1998", "data")}
MARGIN = 0.05

HELPER_CLASSES = {
    "CBackdrop", "CSky", "CEntityWater", "CParticles", "CWaterDisturbance", "CMagnet", "CMuzzleFlash", "CAnimal", "CGun",
    "CLightDirectional", "CStartTrigger", "CLocationTrigger", "CObjectTrigger", "CCreatureTrigger", "CCollisionTrigger",
    "CSequenceTrigger", "CVariableTrigger", "CTimerTrigger", "CBooleanTrigger", "TerrainPlacement", "Player",
    "Player Settings", "AI Command",
}
NON_LEVEL_NAMES = ("BackDrop", "Ocean", "TrnObj_Ocean", "TOcean", "AIBox", "AIShore", "AIConcPier", "Trig_", "Trig",
                   "Teleport", "Occlusion")


def is_land(obj):
    name = obj["name"] or ""
    if not name or name.startswith(NON_LEVEL_NAMES):
        return False
    return obj["class"] not in HELPER_CLASSES


def level_data(data_dir, level):
    """The folder a level's files live in: the retail data folder, or the demo's own."""
    extra = LEVEL_DIRS.get(level)
    return Path(data_dir).parent.joinpath(*extra) if extra else Path(data_dir)


def available_levels(data_dir):
    return [level for level in LEVELS
            if any(p.name.lower() == level + ".scn" for p in level_data(data_dir, level).iterdir())]


def bounds_for(data_dir, level):
    data_dir = level_data(data_dir, level)
    res = analyse_level(data_dir, level)
    land = [o for o in res["objects"] if is_land(o)]
    xs = [o["position"][0] for o in land]
    ys = [o["position"][1] for o in land]
    if not xs:
        raise ValueError("%s: no playable objects" % level)
    lo_x, hi_x = min(xs), max(xs)
    lo_y, hi_y = min(ys), max(ys)
    margin = MARGIN * max(hi_x - lo_x, hi_y - lo_y)
    return {
        "id": level.upper(),
        "min_x": math.floor(lo_x - margin),
        "min_y": math.floor(lo_y - margin),
        "max_x": math.ceil(hi_x + margin),
        "max_y": math.ceil(hi_y + margin),
    }


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--data", type=Path, default=ROOT / "game" / "data")
    args = ap.parse_args(argv)
    out = ROOT / "src" / "host" / "minimap_bounds.inc"
    rows = [bounds_for(args.data, level) for level in available_levels(args.data)]
    lines = ["/* Generated by tools/minimap_bounds.py: world bounds (metres, north +Y, east +X) for the retail levels,",
             " * from each level's playable objects. */"]
    for r in rows:
        lines.append('    { "%s", %d.0f, %d.0f, %d.0f, %d.0f }, /* %s */' % (
            r["id"], r["min_x"], r["min_y"], r["max_x"], r["max_y"], r["id"]))
    text = "\n".join(lines) + "\n"
    out.write_text(text, encoding="ascii")
    for r in rows:
        print("%-4s x:[%7d, %7d] y:[%7d, %7d]  span %6d x %6d" % (
            r["id"], r["min_x"], r["max_x"], r["min_y"], r["max_y"],
            r["max_x"] - r["min_x"], r["max_y"] - r["min_y"]))
    print("wrote %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
