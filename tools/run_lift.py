#!/usr/bin/env python3
"""Lift trespass.exe .text to C: analysis/functions.json -> src/recomp/gen/.

Adapted from sp00nznet/themovies run_lift.py (MIT); drives pcrecomp's generate.py and lift32.

SelfMod is deliberately not lifted: it patches its own immediates at run time, so the host
runs its original bytes (src/host/selfmod.c). Calls into it lift as RECOMP_ICALL.

The functions of src/host/guest_override_list.h lift as lifted_sub_<va> (tools/stable_entries.py). The lift is
written and validated in build/lift-staging, then published into src/recomp/gen (tools/lift_staging.py): only files
whose content changed are rewritten, and analysis/lift_stats.json, written last, marks the lift complete.

    py -3 tools/run_lift.py                 # every catalogued .text function
    py -3 tools/run_lift.py --closure 3000  # entry-point closure only, the rest stubbed
"""
import argparse
import bisect
import json
import re
import sys
import time
from pathlib import Path

from common import ANALYSIS_DIR, CONFIG_DIR, GEN_DIR, TARGET, require_target_exe, use_pcrecomp
from lift_staging import LiftPublishError, create_staging, finish_staging, publish, sweep_staging
from stable_entries import check_folder, listed_overrides, rename_definition

use_pcrecomp("lift", "pe")

from capstone import Cs, CS_ARCH_X86, CS_MODE_32          # noqa: E402
from generate import (EXTENT_REACH, alias_stub, closure, find_splits, true_extent,  # noqa: E402
                      linear_disassemble_function, lift_function_linear, write_chunk)
from lift32 import Lifter                                  # noqa: E402
from pe_analyze import analyze_pe, build_iat_map           # noqa: E402

CATALOG = ANALYSIS_DIR / "functions.json"
SEEDS = ANALYSIS_DIR / "rtti_seeds.json"
STATS = ANALYSIS_DIR / "lift_stats.json"
FAILURE = ANALYSIS_DIR / "lift_failure.json"
EXTRA_ENTRIES = CONFIG_DIR / "extra_entries.json"
DECODER_FIXUPS = CONFIG_DIR / "decoder_fixups.json"
CONSTANT_TARGET = re.compile(r"RECOMP_(?:ICALL|ITAIL)\(0x([0-9A-F]{8})u\)")
VTABLE_SEED_REACH = 0x100
BANNER = "/* Trespasser - AUTO-GENERATED by tools/run_lift.py - derived from the retail binary, do not commit */\n"


def load_catalog(path, lo, hi):
    if not path.exists():
        sys.exit(f"missing {path} -- run tools/analyze.py first")
    catalog = json.loads(path.read_text())
    return {f["address"]: f for f in catalog["functions"] if lo <= f["address"] < hi}


def seed_addresses():
    """RTTI vtable methods, plus entries a run reported as unresolved (config/extra_entries.json)."""
    seeds = set()
    if SEEDS.exists():
        seeds |= {e["address"] for e in json.loads(SEEDS.read_text())}
    if EXTRA_ENTRIES.exists():
        seeds |= {int(x, 16) for x in json.loads(EXTRA_ENTRIES.read_text())["entries"]}
    return seeds


def inject_seeds(byaddr, lo, hi):
    wanted = {a for a in seed_addresses() if lo <= a < hi and a not in byaddr}
    known = sorted(set(byaddr) | wanted)
    following = {a: (known[i + 1] if i + 1 < len(known) else hi) for i, a in enumerate(known)}
    for a in wanted:
        byaddr[a] = {"address": a, "end": min(following[a], a + VTABLE_SEED_REACH),
                     "calls_to": [], "entry_kind": "start"}
    return len(wanted)


def decodable_code(raw, code_start):
    """The section bytes with each known undecodable encoding swapped for its canonical twin."""
    code = bytearray(raw)
    fixups = json.loads(DECODER_FIXUPS.read_text())["fixups"]
    for fix in fixups:
        off = int(fix["va"], 16) - code_start
        expect, decode_as = bytes.fromhex(fix["expect"]), bytes.fromhex(fix["decode_as"])
        if len(expect) != len(decode_as) or bytes(code[off:off + len(expect)]) != expect:
            sys.exit(f"decoder fixup at {fix['va']} does not match this binary")
        code[off:off + len(expect)] = decode_as
    return bytes(code), len(fixups)


def scan_generated(folder, entries, selfmod):
    """What a generated folder holds: constant jump/call targets that are neither a lifted entry nor SelfMod (each
    would fail at run time), the lines of C and the instructions the lifter could not translate."""
    known = {addr for addr, _ in entries}
    bad, lines, unimplemented = set(), 0, 0
    for path in sorted(Path(folder).glob("recomp_*.c")):
        with open(path, encoding="utf-8", errors="replace") as source:
            text = source.read()
        lines += text.count("\n")
        unimplemented += text.count("UNIMPLEMENTED")
        if path.name.startswith("recomp_0"):
            for m in CONSTANT_TARGET.finditer(text):
                target = int(m.group(1), 16)
                if target not in known and not selfmod[0] <= target < selfmod[1]:
                    bad.add(target)
    return sorted(bad), lines, unimplemented


def write_header(out, entries):
    with open(out / "recomp_funcs.h", "w", newline="\n") as f:
        f.write(BANNER + "#pragma once\n#include <stdint.h>\n\n"
                "void recomp_not_lifted(uint32_t va);\n"
                "#define RECOMP_NOT_LIFTED(va) recomp_not_lifted(va)\n\n")
        for _, name in entries:
            f.write(f"void {name}(void);\n")


def write_dispatch(out, entries, text, selfmod):
    with open(out / "recomp_dispatch.c", "w", newline="\n") as f:
        f.write(BANNER + '#include "recomp_types.h"\n#include "recomp_funcs.h"\n\n'
                "const recomp_dispatch_entry_t recomp_dispatch_table[] = {\n")
        for addr, name in sorted(entries):
            f.write(f"    {{ 0x{addr:08X}u, {name} }},\n")
        f.write("};\n"
                f"const uint32_t recomp_dispatch_count = {len(entries)};\n"
                f"const uint32_t trespasser_entry_va = {TARGET['entry_point']}u;\n"
                f"const uint32_t trespasser_image_base = {TARGET['image_base']}u;\n"
                f"const uint32_t trespasser_text_start = 0x{text[0]:08X}u;\n"
                f"const uint32_t trespasser_text_end = 0x{text[1]:08X}u;\n"
                f"const uint32_t trespasser_selfmod_start = 0x{selfmod[0]:08X}u;\n"
                f"const uint32_t trespasser_selfmod_end = 0x{selfmod[1]:08X}u;\n"
                f"const char trespasser_expected_sha256[] = \"{TARGET['sha256']}\";\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--closure", type=int, default=0, metavar="N",
                    help="lift only the call-graph closure from the entry point (N functions); stub the rest")
    ap.add_argument("--roots", default="", help="comma-separated extra closure roots")
    ap.add_argument("--split", type=int, default=250, help="functions per .c file")
    ap.add_argument("--no-alias-sharing", action="store_true",
                    help="lift every alias entry as its own copy of the code (larger output; for bisecting)")
    ap.add_argument("--gen-dir", type=Path, default=GEN_DIR, help="publish here instead of src/recomp/gen (tests)")
    ap.add_argument("--stats-file", type=Path, default=STATS, help="stats file, written last (tests)")
    ap.add_argument("--staging-root", type=Path, default=None, help="staging parent (default build/lift-staging)")
    args = ap.parse_args()

    t_start = time.time()
    exe = require_target_exe()
    info = analyze_pe(str(exe))
    iat = build_iat_map(info)
    sections = {s.name: s for s in info.sections}
    text, sm = sections[".text"], sections["SelfMod"]
    base = info.image_base
    cs, ce = base + text.virtual_address, base + text.virtual_address + text.virtual_size
    selfmod = (base + sm.virtual_address, base + sm.virtual_address + sm.virtual_size)
    if selfmod[0] != int(TARGET["selfmod"]["start"], 16):
        sys.exit("SelfMod is not where config/target.json says it is")
    print(f"[*] .text 0x{cs:08X}-0x{ce:08X}  SelfMod 0x{selfmod[0]:08X}-0x{selfmod[1]:08X}  IAT {len(iat)}")

    byaddr = load_catalog(CATALOG, cs, ce)
    print(f"[*] catalog: {len(byaddr)} functions inside .text")
    print(f"[*] seeded entries not in the catalog: {inject_seeds(byaddr, cs, ce)} injected")

    entry = base + info.entry_point_rva
    if args.closure:
        roots = [entry] + [int(x, 0) for x in args.roots.split(",") if x.strip()]
        chosen = set(closure(byaddr, roots, args.closure))
    else:
        chosen = set(byaddr)
    print(f"[*] lifting {len(chosen)} of {len(byaddr)} functions")

    md = Cs(CS_ARCH_X86, CS_MODE_32)
    md.detail = True
    code, fixups = decodable_code(exe.read_bytes()[text.raw_offset:text.raw_offset + text.raw_size], cs)
    print(f"[*] decoder fixups applied: {fixups}")

    lifter = Lifter(iat_map=iat, lifted=set(byaddr), precise_carry=True, precise_sbb=True)
    out = create_staging(args.staging_root)
    sweep_staging(args.staging_root, keep=out, legacy_dir=args.gen_dir)
    try:
        run(args, out, md, code, cs, ce, selfmod, byaddr, chosen, lifter, t_start)
    finally:
        finish_staging(out)


def run(args, out, md, code, cs, ce, selfmod, byaddr, chosen, lifter, t0):
    stable, renamed = set(listed_overrides()), set()

    entries, chunk, errors, dirty, file_idx = [], [], [], [], 0
    ordered = sorted(byaddr)
    starts = {a for a in ordered if byaddr[a].get("entry_kind") != "alias"}
    t_splits = time.time()
    splits = find_splits(md, code, cs, ce, starts)
    starts -= splits
    print(f"[*] split entries: {len(splits)}, {time.time() - t_splits:.0f}s")

    def flush(force=False):
        nonlocal chunk, file_idx
        if chunk and (force or len(chunk) >= args.split):
            write_chunk(str(out), file_idx, chunk)
            file_idx += 1
            chunk = []

    alias_addrs = sorted(a for a in chosen if byaddr[a].get("entry_kind") == "alias")
    alias_parent = {}

    def claim_aliases(parent, reached):
        """Alias entries whose code this body already holds enter it instead of being copied."""
        if args.no_alias_sharing or not reached:
            return set()
        lo, hi = min(reached), max(reached)
        owned = set()
        for a in alias_addrs[bisect.bisect_left(alias_addrs, lo):bisect.bisect_right(alias_addrs, hi)]:
            if a != parent and a in reached and a not in alias_parent:
                alias_parent[a] = parent
                owned.add(a)
        return owned

    def emit(addr, body):
        name = f"sub_{addr:08X}"
        if addr in stable:
            body = rename_definition(body, addr)
            renamed.add(addr)
        chunk.append((body, addr, name))
        entries.append((addr, name))
        if len(chunk) >= args.split:
            flush()
            print(f"[*]   {len(entries)}/{len(chosen)} ({len(errors)} err)", flush=True)

    def lift_one(addr, end, reached):
        name = f"sub_{addr:08X}"
        try:
            lo = min(reached) if reached else addr
            insns, leaders = (linear_disassemble_function(md, code, cs, lo, end, reached=reached)
                              if end > addr else ([], None))
            if leaders is not None:
                leaders.add(addr)
            if not insns:
                raise ValueError("no instructions decoded")
            body = lift_function_linear(lifter, name, insns, leaders, addr,
                                        alias_entries=claim_aliases(addr, reached))
        except Exception as exc:  # noqa: BLE001 -- recorded and reported, never hidden
            for a in [a for a, p in alias_parent.items() if p == addr]:
                del alias_parent[a]
            body = f"void {name}(void) {{ RECOMP_NOT_LIFTED(0x{addr:08X}u); }}\n"
            errors.append({"address": f"0x{addr:08X}", "error": str(exc)})
        emit(addr, body)

    is_alias = set(alias_addrs)
    todo, added = sorted(a for a in chosen if a not in is_alias) + alias_addrs, 0
    while todo:
        outside = set()
        for addr in todo:
            if addr in alias_parent:
                emit(addr, alias_stub(f"sub_{addr:08X}", addr, f"sub_{alias_parent[addr]:08X}"))
                continue
            reached, behind, called = set(), set(), set()
            end, clean = true_extent(md, code, cs, addr, min(addr + EXTENT_REACH, ce), starts,
                                     reached=reached, behind=behind, called=called)
            outside |= {t for t in behind if t not in reached} | called
            if not clean:
                dirty.append(f"0x{addr:08X}")
            lift_one(addr, end, reached)
        todo = sorted(t for t in outside if cs <= t < ce and t not in byaddr)
        for t in todo:
            byaddr[t] = {"address": t, "end": ce, "calls_to": [], "entry_kind": "start"}
            chosen.add(t)
        added += len(todo)
    print(f"[*] alias entries sharing their parent's body: {len(alias_parent)} of {len(alias_addrs)}")
    print(f"[*] branch and call targets outside the catalog, added as entries: {added}")

    stubs = [a for a in ordered if a not in chosen]
    for a in stubs:
        name = f"sub_{a:08X}"
        body = f"void {name}(void) {{ RECOMP_NOT_LIFTED(0x{a:08X}u); }}\n"
        if a in stable:
            body = rename_definition(body, a)
            renamed.add(a)
        chunk.append((body, a, name))
        entries.append((a, name))
        flush()
    flush(force=True)
    if stable - renamed:
        sys.exit("listed in src/host/guest_override_list.h but not lifted: " +
                 ", ".join(f"0x{a:08X}" for a in sorted(stable - renamed)))

    write_header(out, entries)
    write_dispatch(out, entries, (cs, ce), selfmod)

    unresolved, lines, unimplemented = scan_generated(out, entries, selfmod)
    _, stable_problems = check_folder(out)
    stats = {"target_sha256": TARGET["sha256"], "lifted": len(chosen) - len(errors),
             "closure_stubs": len(stubs), "shared_aliases": len(alias_parent),
             "lift_errors": errors, "no_terminator": dirty,
             "unresolved_constant_targets": [f"0x{t:08X}" for t in unresolved],
             "unimplemented_instructions": unimplemented, "files": file_idx, "lines": lines}
    print("=" * 60)
    print(f"  lifted {stats['lifted']}   closure stubs {len(stubs)}   lift errors {len(errors)}")
    print(f"  no terminator {len(dirty)}   unimplemented instructions {unimplemented}")
    print(f"  unresolved constant targets {len(unresolved)}   stable entries {len(stable)}")
    print(f"  {lines:,} lines of C in {file_idx} files, {time.time() - t0:.1f}s")
    print("=" * 60)
    if errors or unresolved or unimplemented or stable_problems:
        for line in stable_problems:
            print(line)
        if args.stats_file == STATS:
            FAILURE.write_text(json.dumps(dict(stats, stable_entry_problems=stable_problems), indent=1))
        sys.exit("the lift is incomplete, nothing was published: see the counts above and analysis/lift_failure.json")

    try:
        written = publish(out, args.gen_dir, args.stats_file, json.dumps(stats, indent=1))
    except LiftPublishError as error:
        sys.exit(f"the lift was complete but could not be published: {error}")
    if args.stats_file == STATS:
        FAILURE.unlink(missing_ok=True)
    print(f"[*] published: {written} of {file_idx + 2} files rewritten, {len(stable)} stable entries")
    print(f"  stats: {args.stats_file}")


if __name__ == "__main__":
    main()
