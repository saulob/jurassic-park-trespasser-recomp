#!/usr/bin/env python3
"""Writes src/host/profiles: what the one host program knows of each lift it carries.

    py -3 tools/gen_guest_va.py [--check]

guest_va_ids.h        an id for every guest address the host names with GVA(0x...) and GSUB(0x...), and GHOOK_ names.
guest_profile_data.c  per lift (lift116, lift_es117, lift_ptbr117): the address of each id in that lift's executable
                      (0: absent), the patch groups the host ports onto it, its layout and what its generated sources
                      must say about themselves. The active lift's row is copied once at start-up (active_profile.c).
guest_gsub_tables.c   per lift: the lifted function each GSUB id names.
guest_layout.h        the structure fields that are not where 1.0.116 has them (tools/gen_guest_layout.py's values).
<lift>/guest_override_list.h  src/host/guest_override_list.h through the lift's map, sorted, without the overrides of patch
                      groups the lift does not apply (not written for lift116, which uses the list itself).

An address a lift does not have must belong to a patch group that lift does not apply. --check compares what would be
written with the files and exits 1 when they differ.
"""
import argparse
import json
import re
import sys

from common import CONFIG_DIR, GUEST_MAPS_DIR, PROFILES_DIR, ROOT, lift_format
import gen_guest_layout
import guest_map

OUT = ROOT / "src" / "host" / "profiles"
HOST = ROOT / "src" / "host"
USE = re.compile(r"\b(GVA_ID|GVA|GSUB|GHOOK)\(\s*0x([0-9A-Fa-f]{8})\s*\)")
RAW_NAME = re.compile(r"\b(?:sub|lift_hook)_[0-9A-F]{8}\b")
LISTED = re.compile(r"^GUEST_OVERRIDE\(([0-9A-F]{8}), (REQUIRED|OPTIONAL)\)(.*)$", re.M)
GROUPS = ("hand_jump", "add_child", "box_box", "wake")
GROUP_BIT = {"hand_jump": 1, "add_child": 2, "box_box": 4, "wake": 8}
GROUP_SOURCES = {"src/host/patch117_player.c": "hand_jump", "src/host/patch117.c": "add_child"}
BASELINE = "en-116"
LIFTS = (  # enum order of jpt_lift_t
    ("lift116", "JPT_LIFT_116", BASELINE),
    ("lift_es117", "JPT_LIFT_ES117", "es-117"),
    ("lift_ptbr117", "JPT_LIFT_PTBR117", "ptbr-117"),
)
RESOLVED = ("identical", "aligned", "data", "decided")
BANNER = "/* Generated by tools/gen_guest_va.py. */\n"


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def host_text(path):
    text = path.read_text(encoding="utf-8", errors="replace")
    return guest_map.STRING.sub(" ", guest_map.COMMENT.sub(" ", text))


def host_uses():
    """kind -> {1.0.116 address: [source files]} from GVA/GSUB/GHOOK in the host's code; a raw lifted name is an error."""
    uses = {"GVA": {}, "GSUB": {}, "GHOOK": {}}
    raw = []
    for path in sorted(HOST.rglob("*")):
        rel = path.relative_to(ROOT).as_posix()
        if path.suffix not in (".c", ".h", ".cpp") or "/profiles/" in rel or path.name in ("guest_override_list.h",
                                                                                           "lift_hook_list.h"):
            continue
        text = host_text(path)
        for kind, va in USE.findall(text):
            kind = "GVA" if kind == "GVA_ID" else kind
            uses[kind].setdefault(int(va, 16), set()).add(rel)
        raw += [f"{rel}: {m}" for m in RAW_NAME.findall(text)]
    return uses, raw


def profile_facts(profile_id):
    if profile_id == BASELINE:
        target = read_json(CONFIG_DIR / "target.json")
        groups = {g: True for g in GROUPS}
        mapping = None
    else:
        target = read_json(PROFILES_DIR / f"{profile_id}.json")
        groups = target["patch117"]
        stored = read_json(GUEST_MAPS_DIR / f"{profile_id}.json")["addresses"]
        mapping = {int(k, 16): v for k, v in stored.items()}
    return target, groups, mapping


def mapped_address(mapping, va):
    """The lift's address of a 1.0.116 address; None when it is absent; an error when it is neither."""
    if mapping is None:
        return va
    row = mapping.get(va)
    if row is None:
        sys.exit(f"0x{va:08X} is used by the host but is not in the guest map of the profile: "
                 "py -3 tools/guest_map.py <id> --write")
    if row["class"] in RESOLVED:
        return int(row["to"], 16)
    if row["class"] == "absent":
        return None
    sys.exit(f"0x{va:08X} is {row['class']} in the guest map: the lift cannot be used until it is proven")


def gate_of(va, rows):
    """The patch group that explains an address being absent in a lift: the group that lists it, or the group whose
    source file reads it."""
    groups = read_json(CONFIG_DIR / "patch117_groups.json")
    hit = [name for name, g in groups.items() if f"{va:08X}" in g["hooks"] + g["overrides"]]
    if not hit:
        hit = sorted({GROUP_SOURCES[f] for f in rows if f in GROUP_SOURCES})
    if len(hit) != 1:
        sys.exit(f"0x{va:08X} is absent in a lift but no single patch group explains it: {hit}")
    return hit[0]


def layout_values():
    out = {}
    for lift, _, profile_id in LIFTS:
        if profile_id == BASELINE:
            out[lift] = {d["name"]: d["value"] for d in gen_guest_layout.descriptors()}
            continue
        found, errors = gen_guest_layout.values(profile_id)
        if errors:
            sys.exit(f"{lift}: " + "; ".join(errors))
        out[lift] = found
    return out


def render_layout_header():
    lines = [BANNER.rstrip("\n"), "/* The structure fields that are not where 1.0.116 has them, as the active lift's executable lays them",
             " * out (config/host_offsets.json). Every other field the host reads is at its 1.0.116 offset. */",
             "#ifndef JPT_GUEST_LAYOUT_H", "#define JPT_GUEST_LAYOUT_H", "", "#include <stdint.h>", "",
             "typedef struct {"]
    for d in gen_guest_layout.descriptors():
        lines.append(f"    uint32_t {d['name'].lower()}; /* {d['struct']}: {d['field']} */")
    lines += ["} jpt_layout_t;", "", "extern jpt_layout_t jpt_layout;", ""]
    for d in gen_guest_layout.descriptors():
        lines.append(f"#define GLAYOUT_{d['name']} (jpt_layout.{d['name'].lower()})")
    return "\n".join(lines + ["", "#endif", ""])


def render_ids(gva, gsub, hooks):
    lines = [BANNER.rstrip("\n"), "#ifndef JPT_GUEST_VA_IDS_H", "#define JPT_GUEST_VA_IDS_H", "", "enum {"]
    lines += [f"    GVAI_0x{va:08X}," for va in gva] + ["    JPT_GVA_COUNT", "};", "", "enum {"]
    lines += [f"    GSUBI_0x{va:08X}," for va in gsub] + ["    JPT_GSUB_COUNT", "};", ""]
    lines += [f"#define GHOOK_0x{va:08X} lift_hook_{va:08X}" for va in hooks]
    return "\n".join(lines + ["", "#endif", ""])


def render_profile_data(gva, tables, gates, patch, expected, layouts):
    lines = [BANNER.rstrip("\n"), '#include "active_profile.h"', "",
             "const unsigned char jpt_gva_gate[JPT_GVA_COUNT] = {"]
    lines += [f"    {gates[va]}, /* 0x{va:08X} */" for va in gva] + ["};", ""]
    lines += ["const uint32_t jpt_gva_canonical[JPT_GVA_COUNT] = {"] + [f"    0x{va:08X}u," for va in gva] + ["};", ""]
    lines += ["const jpt_lift_data_t jpt_lift_data[JPT_LIFT_COUNT] = {"]
    for lift, enum, profile_id in LIFTS:
        meta = expected[lift]
        lines += [f"    [{enum}] = {{", f'        "{lift}",',
                  f'        {{ "{lift}", "{profile_id}", "{meta["sha256"]}", {lift_format()}u, 0u,',
                  f'          {meta["entry_point"]}u, {meta["image_base"]}u, 0u, 0u, {meta["selfmod"]["start"]}u, 0u }},',
                  f'        {meta["size_of_image"]}u,', f"        {patch[lift]}u,", "        {"]
        lines += [f"            0x{int(layouts[lift][d['name']], 16):X}u, /* {d['name']} */"
                  for d in gen_guest_layout.descriptors()]
        lines += ["        }, {"]
        lines += [f"            0x{tables[lift][va]:08X}u," if tables[lift][va] else f"            0u, /* 0x{va:08X} */"
                  for va in gva]
        lines += ["        }", "    },"]
    return "\n".join(lines + ["};", ""])


def render_gsub_tables(gsub, tables):
    lines = [BANNER.rstrip("\n"), '#include "active_profile.h"', "", "typedef void (*jpt_gsub_fn_t)(void);", ""]
    for lift, _, _ in LIFTS:
        lines += [f"void {lift}_sub_{tables[lift][va]:08X}(void);" for va in gsub]
    lines += ["", "const jpt_gsub_fn_t jpt_gsub_by_lift[JPT_LIFT_COUNT][JPT_GSUB_COUNT] = {"]
    for lift, enum, _ in LIFTS:
        lines += [f"    [{enum}] = {{"] + [f"        {lift}_sub_{tables[lift][va]:08X}," for va in gsub] + ["    },"]
    return "\n".join(lines + ["};", ""])


def render_override_list(lift_map, skipped):
    source = (HOST / "guest_override_list.h").read_text(encoding="utf-8")
    head = source[:source.index("GUEST_OVERRIDE(")]
    rows = []
    for va, need, rest in LISTED.findall(source):
        v = int(va, 16)
        if v in skipped:
            continue
        address = mapped_address(lift_map, v)
        if address is not None:
            rows.append((address, need, rest))
    rows.sort()
    return head + "".join(f"GUEST_OVERRIDE({t:08X}, {need}){rest}\n" for t, need, rest in rows)


def files_for():
    uses, raw = host_uses()
    if raw:
        sys.exit("the host names lifted functions or hooks directly (use GSUB/GHOOK): " + ", ".join(raw[:6]))
    gva, gsub, hooks = (sorted(uses[k]) for k in ("GVA", "GSUB", "GHOOK"))
    listed = {int(m, 16) for m in re.findall(r"^LIFT_HOOK\(([0-9A-F]{8})\)", (HOST / "lift_hook_list.h").read_text(
        encoding="utf-8"), re.M)}
    if set(hooks) != listed:
        sys.exit("the hook list and the host's GHOOK functions differ: "
                 + ", ".join(f"0x{v:08X}" for v in sorted(set(hooks) ^ listed)))
    groups_json = read_json(CONFIG_DIR / "patch117_groups.json")
    tables, patch, expected, gates = {}, {}, {}, {va: 0 for va in gva}
    for lift, _, profile_id in LIFTS:
        target, groups, mapping = profile_facts(profile_id)
        expected[lift] = target
        patch[lift] = sum(GROUP_BIT[g] for g in GROUPS if groups[g])
        tables[lift] = {}
        for va in gva:
            address = mapped_address(mapping, va)
            tables[lift][va] = address or 0
            if address is None:
                group = gate_of(va, uses["GVA"][va])
                if groups[group]:
                    sys.exit(f"{lift}: 0x{va:08X} is absent but the patch group {group} that uses it is applied")
                gates[va] = GROUP_BIT[group]
        for va in gsub:
            address = mapped_address(mapping, va)
            if address is None:
                sys.exit(f"{lift}: GSUB(0x{va:08X}) has no function in this lift")
            tables[lift][va] = address
    for lift, _, profile_id in LIFTS:
        for va in gva:
            if not tables[lift][va] and not gates[va]:
                sys.exit(f"{lift}: 0x{va:08X} is absent and no patch group explains it")
    missing = set(groups_json) - set(GROUPS)
    if missing:
        sys.exit(f"patch groups the generator does not know: {sorted(missing)}")
    files = {
        "guest_va_ids.h": render_ids(gva, gsub, hooks),
        "guest_layout.h": render_layout_header(),
        "guest_profile_data.c": render_profile_data(gva, tables, gates, patch, expected, layout_values()),
        "guest_gsub_tables.c": render_gsub_tables(gsub, tables),
    }
    for lift, _, profile_id in LIFTS:
        if profile_id == BASELINE:
            continue
        _, groups, mapping = profile_facts(profile_id)
        skipped = {int(va, 16) for name, g in groups_json.items() if not groups[name] for va in g["overrides"]}
        files[f"{lift}/guest_override_list.h"] = render_override_list(mapping, skipped)
    return files


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    stale = []
    for name, text in files_for().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)} ({text.count(chr(10))} lines)")
    for name in stale:
        print("stale:", name)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
