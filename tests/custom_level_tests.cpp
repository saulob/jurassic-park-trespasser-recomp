// What kRar5 holds.
static std::string RarText() {
    std::string text;
    for (int i = 0; i < 1500; ++i) text += "line " + std::to_string(i) + " of the level\n";
    return text;
}

static std::string RarCalls() {
    std::string bytes(20000, '\0');
    for (size_t i = 0; i < bytes.size(); ++i) bytes[i] = char(i % 9 == 0 ? 0xE8 : (i * 7) & 255);
    return bytes;
}

static std::string RarDelta() {
    std::string bytes(16000, '\0');
    for (size_t i = 0; i < bytes.size(); ++i) bytes[i] = char(((i / 4) * (i % 4 + 1)) & 255);
    return bytes;
}

